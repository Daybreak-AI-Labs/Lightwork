const {test,expect}=require('@playwright/test');
const fs=require('node:fs');
test('recorded learning receipt downloads and checks through native UI',async({page,context,baseURL},info)=>{
  await context.route('**/*',route=>new URL(route.request().url()).origin===new URL(baseURL).origin?route.continue():route.abort());
  const errors=[];page.on('pageerror',error=>errors.push(error.message));
  await page.setViewportSize({width:390,height:900});
  await page.goto('/audit/evolution-ledger');
  await expect(page.getByText('Stored history checked.',{exact:true})).toBeVisible();
  await expect(page.getByText('Stored chain checks match',{exact:true})).toBeVisible();
  const download=page.waitForEvent('download');
  await page.getByRole('link',{name:'Download receipt',exact:true}).click();
  const file=await download;
  const path=info.outputPath('downloaded-receipt.json');await file.saveAs(path);
  expect(fs.readFileSync(path,'utf8')).not.toContain('synthetic-private-record');
  expect(fs.readFileSync(path,'utf8')).not.toContain('Synthetic private summary');
  await page.locator('#elv-receipt').setInputFiles(path);
  await page.getByRole('button',{name:'Check receipt',exact:true}).click();
  await expect(page.locator('#elv-verdict')).toHaveText('This receipt matches a change in the current workspace history.');
  await expect(page.locator('#elv-verdict-detail')).toContainText('does not prove who created');
  expect(errors).toEqual([]);
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1)).toBe(true);
  await page.getByRole('button',{name:'Open Lightwork Copilot',exact:true}).click();
  const search = page.getByRole('searchbox',{name:'Find a control on this page'});
  await expect(search).toBeVisible();
  await expect(page.getByRole('button',{name:'Check learning history',exact:true})).toBeVisible();
  await search.fill('a control that does not exist');
  await expect(page.locator('#mv-product-operation-empty')).toBeVisible();
  await expect(page.getByRole('button',{name:'Check learning history',exact:true})).toBeHidden();
  await search.fill('learning history');
  await expect(page.locator('#mv-product-operation-empty')).toBeHidden();
  await page.getByRole('button',{name:'Check learning history',exact:true}).click();
  await expect(page.locator('#mv-product-operation-form')).toContainText('recorded changes');
  await page.screenshot({path:info.outputPath('learning-receipt-phone.png'),fullPage:true});
});
