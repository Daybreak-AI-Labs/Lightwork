const {test,expect}=require('@playwright/test');
const axe=require('axe-core');

test('real evidence, task review, recovery, responsive layout and unsaved native handoff',async({page,request,context,baseURL},testInfo)=>{
  await context.route('**/*',route=>new URL(route.request().url()).origin===new URL(baseURL).origin?route.continue():route.abort('blockedbyclient'));
  const errors=[];page.on('pageerror',error=>errors.push(error.message));
  await page.goto('/ekko');
  await expect(page.locator('#ekko-discovery-progress')).toContainText('0 activities');
  await expect(page.getByRole('button',{name:'Review this opportunity'})).toHaveCount(0);
  const seeded=await request.post('/__browser_fixture/intent-value-ekko');
  expect(seeded.ok(),await seeded.text()).toBeTruthy();
  await page.getByRole('button',{name:'Look for repeated work'}).click();
  await expect(page.locator('#ekko-discovery-progress')).toContainText('4 activities across 2 days');
  await expect(page.locator('#ekko-opportunities')).toContainText('2 separate occurrences');
  await expect(page.locator('#ekko-opportunities')).not.toContainText('% sure');
  await page.getByText('Why Ekko suggested this',{exact:true}).click();
  await expect(page.locator('#ekko-opportunities')).toContainText('time savings are not known');
  const open=page.getByRole('button',{name:'Review this opportunity'});
  await open.focus();await page.keyboard.press('Enter');
  await expect(page.locator('#ekko-review-heading')).toBeFocused();
  let submissions=0;page.on('request',r=>{if(r.url().endsWith('/handoff')) submissions++;});
  await page.getByRole('button',{name:'Open workflow draft'}).click();
  expect(submissions).toBe(0);
  await page.getByLabel('What job are you doing?').fill('Prepare the weekly sales summary');
  await page.getByLabel('What does the job start with?').fill('The sales export I select for the week');
  await page.getByLabel('What should the finished result look like?').fill('A presentation with totals and exceptions');
  await page.getByLabel('What will a person check?').fill('I check figures before sharing with the team');
  await page.getByText('The plan your draft will contain',{exact:true}).click();
  await expect(page.locator('#ekko-review')).toContainText('You review the finished draft');
  await page.evaluate(()=>window.scrollTo(0,0));
  await page.screenshot({path:testInfo.outputPath('ekko-desktop.png'),fullPage:true});
  await page.setViewportSize({width:390,height:844});
  const widths=await page.evaluate(()=>[document.documentElement.scrollWidth,document.documentElement.clientWidth]);
  expect(widths[0]).toBeLessThanOrEqual(widths[1]+1);
  await page.addScriptTag({content:axe.source});
  const audit=await page.evaluate(async()=>axe.run(document.getElementById('ekko-review'),{runOnly:{type:'tag',values:['wcag2a','wcag2aa','wcag21aa']}}));
  expect(audit.violations).toEqual([]);
  await page.evaluate(()=>window.scrollTo(0,0));
  await page.screenshot({path:testInfo.outputPath('ekko-narrow.png'),fullPage:true});
  await context.route('**/api/v1/ekko/candidates/*/handoff',route=>route.fulfill({status:409,contentType:'application/json',body:JSON.stringify({detail:'The evidence changed. Refresh the suggestions and review this pattern again before drafting.'})}));
  await page.getByRole('button',{name:'Open workflow draft'}).click();
  await expect(page.locator('#ekko-review-message')).toContainText('Your notes are still here');
  await expect(page.getByLabel('What job are you doing?')).toHaveValue('Prepare the weekly sales summary');
  await context.unroute('**/api/v1/ekko/candidates/*/handoff');
  await page.getByRole('button',{name:'Look for repeated work'}).click();
  await page.getByRole('button',{name:'Review this opportunity'}).click();
  const definitionsBefore=await (await request.get('/api/v1/flows')).json();
  // Preserve the real server response before Chromium detaches it on navigation.
  let nativeHandoff;
  await context.route('**/api/v1/ekko/candidates/*/handoff',async route=>{
    const response=await route.fetch();
    nativeHandoff={ok:response.ok(),body:await response.json()};
    await route.fulfill({response});
  });
  await page.getByRole('button',{name:'Open workflow draft'}).click();
  await expect(page).toHaveURL(/\/flows\/designer$/);
  const {ok,body}=nativeHandoff;expect(ok,JSON.stringify(body)).toBeTruthy();
  expect(body.unsaved).toBe(true);expect(body.requires_human_approval).toBe(true);
  expect(body.flow.nodes.find(node=>node.id==='review-result').kind).toBe('approval');
  expect(await (await request.get('/api/v1/flows')).json()).toEqual(definitionsBefore);
  await expect(page).toHaveURL(/\/flows\/designer$/);
  await expect(page.getByRole('textbox',{name:'Flow name',exact:true})).toHaveValue('Prepare the weekly sales summary');
  expect(errors).toEqual([]);
});

test('changing devices clears review notes and old evidence',async({page})=>{
  await page.goto('/ekko');
  await page.getByRole('button',{name:'Review this opportunity'}).click();
  await page.getByLabel('What job are you doing?').fill('Notes for the previous device');
  await page.getByLabel('Device',{exact:true}).selectOption('__other__');
  await page.getByRole('textbox',{name:'Name of the other device'}).fill('second-device');
  await page.getByRole('button',{name:'Use this device'}).click();
  await expect(page.locator('#ekko-review')).toBeHidden();
  await expect(page.locator('#ekko-review-goal')).toHaveValue('');
  await expect(page.locator('#ekko-discovery-progress')).toContainText('0 activities');
  await expect(page.getByRole('button',{name:'Review this opportunity'})).toHaveCount(0);
});

test('Copilot uses a fresh protected review without exporting activity or starting work',async({page,request})=>{
  await page.goto('/ekko');
  await expect(page.getByRole('button',{name:'Review this opportunity'})).toBeVisible();
  const catalogResponse=await request.post('/api/v1/copilot/product-operations/catalog',{data:{page:'/ekko',selection:{}}});
  expect(catalogResponse.ok(),await catalogResponse.text()).toBeTruthy();
  const catalog=await catalogResponse.json();
  const operation=catalog.operations.find(item=>item.id==='learning.ekko_discovery_review');
  expect(operation.available).toBe(true);expect(operation.details).toEqual({});
  const input={page:'/ekko',selection:{},operation:operation.id,context:catalog.context,revision:operation.revision,arguments:{}};
  expect((await request.post('/api/v1/copilot/product-operations/prepare',{data:{...input,revision:'0'.repeat(64)}})).status()).toBe(409);
  const response=await request.post('/api/v1/copilot/product-operations/prepare',{data:input});
  expect(response.ok(),await response.text()).toBeTruthy();
  const preview=await response.json();expect(preview.read_only).toBe(true);
  const review=preview.details.ekko_discovery_review;
  expect(Object.keys(review).sort()).toEqual(['context','scope']);
  await page.getByRole('button',{name:'Review this opportunity'}).click();
  await page.getByLabel('What job are you doing?').fill('Keep my entered task context');
  const opened=await page.evaluate(async context=>window.LightworkEkkoRecording.openDiscovery({}, {context,isCurrent:()=>true}),review.context);
  expect(opened).toBe(true);
  await expect(page.locator('#ekko-opportunities-heading')).toBeFocused();
  await expect(page.getByLabel('What job are you doing?')).toHaveValue('Keep my entered task context');
  const stale=await page.evaluate(async()=>window.LightworkEkkoRecording.openDiscovery({}, {context:'0'.repeat(64),isCurrent:()=>true}));
  expect(stale).toBe(false);
  await page.evaluate(()=>document.dispatchEvent(new CustomEvent('lightwork:workspace-changed')));
  await expect(page.locator('#ekko-review')).toBeHidden();
  await expect(page.locator('#ekko-review-goal')).toHaveValue('');
});
