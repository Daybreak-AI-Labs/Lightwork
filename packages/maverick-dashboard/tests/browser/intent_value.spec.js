const {test,expect}=require('@playwright/test');
const axe=require('axe-core');
const api='/api/v1/intent-value';

test('intent to evidence, correction, retained controls and native draft',async({page,request,context,baseURL},testInfo)=>{
  await context.route('**/*',route=>new URL(route.request().url()).origin===new URL(baseURL).origin?route.continue():route.abort('blockedbyclient'));
  const errors=[];page.on('pageerror',error=>errors.push(error.message));
  await page.goto('/work-value');
  await expect(page.locator('#iv-report')).toBeVisible();
  await expect(page.locator('[data-metric="performed"] strong')).toHaveText('3');
  await page.locator('[data-metric="gross"]').click();
  await expect(page.locator('#iv-explanation')).toContainText('exact contributing work population');
  await page.locator('#iv-work button').first().click();
  const dialog=page.locator('#iv-detail');
  await expect(dialog).toContainText('Provisional Lightwork planning assumption');
  await expect(dialog).toContainText('goal_end: succeeded');
  await expect(dialog.getByRole('button',{name:'Mark this result complete (optional)'})).toHaveCount(0);
  await dialog.getByLabel('Corrected activity').selectOption(['rfp.review']);
  await dialog.getByLabel('Correction reason').fill('The completed work reviewed an existing RFP.');
  await dialog.getByRole('button',{name:'Correct and recalculate',exact:true}).click();
  await expect(dialog.locator('#iv-detail-title')).toHaveText('Review RFP');
  await expect(dialog).toContainText('Version 2:');
  await page.locator('#iv-detail-close').click();
  const response=await request.get(api),report=await response.json();
  expect(report.totals.performed_work).toBe(3);
  const copilot=await request.post('/api/v1/copilot',{data:{message:'What is Lightwork delivering across our company?',page:'/work-value'}});
  expect(copilot.ok(),await copilot.text()).toBeTruthy();
  expect((await copilot.json()).metrics.totals).toEqual((await (await request.get(api+'?scope=company')).json()).totals);
  const rfp=page.locator('.iv-opportunity').filter({has:page.getByRole('heading',{name:'Draft RFP',exact:true})});
  await rfp.getByRole('button',{name:'Review opportunity'}).click();
  await expect(dialog).toContainText('potential labor value');
  await expect(dialog).toContainText('Cost and labor assumptions still need qualification');
  await dialog.getByRole('checkbox',{name:'Keep manual: Draft RFP using supplied material'}).check();
  await dialog.getByRole('button',{name:'Build reviewable workflow draft'}).click();
  await expect(dialog.getByRole('link',{name:'Open draft in workflow builder'})).toBeVisible();
  const href=await dialog.getByRole('link',{name:'Open draft in workflow builder'}).getAttribute('href');
  const definitions=await (await request.get('/api/v1/flows')).json();
  const proposal=(await (await request.get(api+'/opportunities')).json()).opportunities.find(item=>item.intent==='rfp.draft');
  expect(proposal.draft_id).toBeTruthy();
  expect(proposal.outcome.state).toBe('draft');
  expect(JSON.stringify(definitions)).toContain(proposal.draft_id);
  const replay=await request.post(api+'/opportunities/'+proposal.id+'/build',{data:{revision:proposal.revision}});
  expect(replay.ok(),await replay.text()).toBeTruthy();expect((await replay.json()).draft_id).toBe(proposal.draft_id);
  await page.locator('#iv-detail-close').click();
  await page.screenshot({path:testInfo.outputPath('work-value-desktop.png'),fullPage:true});
  await page.goto(href);await expect(page).toHaveURL(new RegExp('/flows/designer/'+proposal.draft_id));
  await expect(page.getByRole('textbox',{name:'Flow name',exact:true})).toHaveValue('Draft RFP with human review');
  expect(errors).toEqual([]);
});

test('narrow layout, keyboard explanations, unavailable state and accessibility',async({page,context,baseURL},testInfo)=>{
  await context.route('**/*',route=>new URL(route.request().url()).origin===new URL(baseURL).origin?route.continue():route.abort('blockedbyclient'));
  await page.setViewportSize({width:390,height:844});
  await page.goto('/work-value');await expect(page.locator('#iv-report')).toBeVisible();
  const widths=await page.evaluate(()=>[document.documentElement.scrollWidth,document.documentElement.clientWidth]);
  expect(widths[0]).toBeLessThanOrEqual(widths[1]+1);
  await page.locator('[data-metric="cost"]').focus();await page.keyboard.press('Enter');
  await expect(page.locator('#iv-contributions')).toBeFocused();
  await page.addScriptTag({content:axe.source});
  const audit=await page.evaluate(async()=>await axe.run(document.getElementById('iv-app'),{runOnly:{type:'tag',values:['wcag2a','wcag2aa','wcag21aa']}}));
  expect(audit.violations).toEqual([]);
  await page.screenshot({path:testInfo.outputPath('work-value-narrow.png'),fullPage:true});
  await context.route('**/api/v1/intent-value?*',route=>route.fulfill({status:503,contentType:'application/json',body:JSON.stringify({detail:'Synthetic unavailable evidence'})}));
  await page.getByRole('button',{name:'Update report'}).click();
  await expect(page.locator('#iv-status')).toContainText('no zero-value claim');
  await expect(page.locator('#iv-report')).toBeHidden();
  await expect(page.locator('#iv-error')).toHaveText('Synthetic unavailable evidence');
  await context.unroute('**/api/v1/intent-value?*');
  await page.getByRole('button',{name:'Retry loading'}).click();await expect(page.locator('#iv-report')).toBeVisible();
});
